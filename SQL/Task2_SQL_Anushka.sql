DROP TABLE TASK2_OT;
CREATE TABLE TASK2_OT(
ORDER_ID TEXT,
ORDER_DATE DATE,
CUSTOMER_ID TEXT,
PRODUCT_ID VARCHAR(50),
CATEGORY VARCHAR(50),
SUB_CATEGORY VARCHAR(50),
PRODUCT_NAME TEXT,
SALES NUMERIC(10,2),
QUANTITY INT,
DISCOUNT NUMERIC(10,2),
PROFIT NUMERIC(10,2)
);

